"""Collect the report's numbers from the running system into report/results.md.

Every figure comes from a query against MySQL, Kafka's offsets, the saved model or
report/evaluation.csv, so the report never quotes a number nobody measured.
Run it after a full replay has finished (both consumer groups at lag 0):
    python scripts/reset_demo.py
    python -m src.processor        (terminal 1)
    python -m src.forecaster       (terminal 2)
    python -m src.producer --rate 200
    python scripts/collect_results.py
"""
import sys
from datetime import datetime, timezone
from pathlib import Path

# Let `python scripts/collect_results.py` import the src package from the repo root.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import joblib  # noqa: E402
import pandas as pd  # noqa: E402
import sqlalchemy as sa  # noqa: E402
from kafka import KafkaAdminClient, KafkaConsumer, TopicPartition  # noqa: E402

from scripts import evaluate  # noqa: E402
from src import config, train_model  # noqa: E402

RESULTS = config.ROOT / "report" / "results.md"


def mysql_engine():
    url = sa.engine.URL.create("mysql+pymysql", username=config.MYSQL_USER, password=config.MYSQL_PASSWORD,
                               host=config.MYSQL_HOST, port=config.MYSQL_PORT, database=config.MYSQL_DATABASE)
    return sa.create_engine(url)


def query(engine, sql):
    with engine.connect() as db:
        return pd.read_sql(sa.text(sql), db)


def kafka_offsets():
    """Newest offset on the topic, and the committed offset of each consumer group."""
    partition = TopicPartition(config.KAFKA_TOPIC, 0)
    consumer = KafkaConsumer(bootstrap_servers=config.KAFKA_BOOTSTRAP_SERVERS)
    end = consumer.end_offsets([partition])[partition]
    consumer.close()
    admin = KafkaAdminClient(bootstrap_servers=config.KAFKA_BOOTSTRAP_SERVERS)
    committed = admin.list_group_offsets({config.CONSUMER_GROUP: None, config.FORECAST_GROUP: None})
    admin.close()
    groups = {group: offsets[partition].offset if partition in offsets else None
              for group, offsets in committed.items()}
    return end, groups


def main():
    engine = mysql_engine()
    end_offset, groups = kafka_offsets()
    m = query(engine, "SELECT * FROM metrics_current WHERE id = 1").iloc[0]
    readings = query(engine, "SELECT kafka_offset, seq, event_time, temperature, is_anomaly, produced_at, stored_at FROM readings ORDER BY id")
    hourly_rows = query(engine, "SELECT COUNT(*) AS n FROM hourly_stats").n[0]
    forecasts = query(engine, "SELECT f.target_time, f.predicted_temperature, f.lower, f.upper, r.temperature AS actual "
                              "FROM forecasts f LEFT JOIN readings r ON r.event_time = f.target_time")
    n_forecasts = query(engine, "SELECT COUNT(DISTINCT made_at_event_time) AS n FROM forecasts").n[0]

    peak = readings.loc[readings.temperature.idxmax()]
    low = readings.loc[readings.temperature.idxmin()]
    lag_ms = (readings.stored_at - readings.produced_at).dt.total_seconds() * 1000
    replay_s = (readings.produced_at.max() - readings.produced_at.min()).total_seconds()

    windows = evaluate.load_windows()
    score = evaluate.score_against_windows(list(readings.event_time), list(readings.is_anomaly), windows)

    matched = forecasts.dropna(subset=["actual"])
    errors = (matched.predicted_temperature - matched.actual).abs()
    inside = ((matched.actual >= matched.lower) & (matched.actual <= matched.upper)).mean() * 100

    model = joblib.load(config.MODEL_PATH)["model"]
    training = train_model.load_training_rows()
    train_rows = train_model.build_training_rows([t for _, t in training])
    train_flagged = sum(1 for p in model.predict(train_rows) if p == -1)

    comparison = pd.read_csv(config.ROOT / "report" / "evaluation.csv")
    # Whole minutes; "Int64" leaves a missed window empty instead of turning the column into floats.
    for column in [c for c in comparison.columns if c.startswith("delay_")]:
        comparison[column] = comparison[column].astype("Int64")

    window_lines = []
    for i, ((start, end), delay) in enumerate(zip(windows, score["delays_min"]), start=1):
        in_window = readings[(readings.event_time >= start) & (readings.event_time <= end)]
        first = in_window[in_window.is_anomaly == 1].event_time.min()
        window_lines.append(f"| {i} | {start:%Y-%m-%d %H:%M} to {end:%Y-%m-%d %H:%M} | {int(in_window.is_anomaly.sum())} | "
                            + (f"{first:%Y-%m-%d %H:%M} | {delay}" if delay is not None else "none | -") + " |")

    text = f"""# Results

Generated by `python scripts/collect_results.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC, from the state
left by one full replay on a reset system: `python scripts/reset_demo.py`, then the processor and the forecaster, then
`python -m src.producer --rate 200` (dashboard closed). Every number below is read from MySQL, Kafka, the saved model
or `report/evaluation.csv` by that script.

## Stream
| Measure | Value | Source |
| --- | --- | --- |
| Events sent (newest offset on the topic) | {end_offset:,} | Kafka `end_offsets` |
| Rows stored | {len(readings):,} | `SELECT COUNT(*) FROM readings` |
| Distinct Kafka offsets stored | {readings.kafka_offset.nunique():,} (no duplicates: {readings.kafka_offset.is_unique}) | `readings` |
| Events processed | {int(m.events_processed):,} | `metrics_current` |
| Late events dropped | {int(m.late_events_dropped)} | `metrics_current` |
| Processed + dropped = sent | {int(m.events_processed) + int(m.late_events_dropped):,} = {end_offset:,} | |
| Event-time range | {readings.event_time.min():%Y-%m-%d %H:%M} to {readings.event_time.max():%Y-%m-%d %H:%M} | `readings` |
| Replay duration (first to last send) | {replay_s:.0f} s ({len(readings) / replay_s:.0f} readings/s) | `produced_at` |

## Temperature
| Measure | Value | Event time |
| --- | --- | --- |
| Peak | {peak.temperature:.2f} | {peak.event_time:%Y-%m-%d %H:%M} |
| Minimum | {low.temperature:.2f} | {low.event_time:%Y-%m-%d %H:%M} |

## Anomalies (IsolationForest, 4 features, contamination 0.01)
- Readings flagged: **{int(m.anomalies_flagged)}** of {len(readings):,} ({score['flagged_pct']:.2f}%); flags in `readings`: {score['flags']}.
- Labelled failure windows with at least one flag: **{score['windows_hit']} of {len(windows)}**.
- Flags inside labelled windows: {score['inside']}; outside: {score['outside']} (unlabelled, not proven false).

| Window | Labelled period | Flags inside | First flag | Delay from window start (min) |
| --- | --- | --- | --- | --- |
{chr(10).join(window_lines)}

## Pipeline lag (stored_at minus produced_at, per reading, at --rate 200)
| Average | Median | 95th percentile | Maximum |
| --- | --- | --- | --- |
| {lag_ms.mean():.1f} ms | {lag_ms.median():.0f} ms | {lag_ms.quantile(0.95):.0f} ms | {lag_ms.max():.0f} ms |

## Consumer groups (committed offset vs {end_offset:,} events on the topic)
| Group | Committed offset | Lag |
| --- | --- | --- |
| {config.CONSUMER_GROUP} (processor) | {groups.get(config.CONSUMER_GROUP)} | {end_offset - groups[config.CONSUMER_GROUP] if groups.get(config.CONSUMER_GROUP) is not None else '-'} |
| {config.FORECAST_GROUP} (forecaster) | {groups.get(config.FORECAST_GROUP)} | {end_offset - groups[config.FORECAST_GROUP] if groups.get(config.FORECAST_GROUP) is not None else '-'} |

## Forecaster and hourly window
- Forecasts made (ARIMA(1,1,1) fits): {n_forecasts:,}; forecast points stored: {len(forecasts):,}.
- Forecast points whose target time has a stored reading: {len(matched):,}. Mean absolute error {errors.mean():.2f},
  median {errors.median():.2f}, maximum {errors.max():.2f}; the actual reading fell inside the 95% interval for
  {inside:.1f}% of them.
- Hours in `hourly_stats`: {hourly_rows:,}.

## Training (saved model)
- Training rows used: {len(train_rows):,} (rows {len(training) - len(train_rows)}-{len(training) - 1} of the CSV, the first
  {len(training) - len(train_rows)} only warm up the window), {training[len(training) - len(train_rows)][0]} to {training[-1][0]}.
- Training rows the saved model flags: {train_flagged} ({train_flagged / len(train_rows):.2%}).

## Model comparison (from `python scripts/evaluate.py`, report/evaluation.csv)
{evaluate.markdown_table(comparison)}
"""
    RESULTS.write_text(text)
    print(text)
    print(f"Wrote {RESULTS.relative_to(config.ROOT)}")


if __name__ == "__main__":
    main()
