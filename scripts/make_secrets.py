"""Write .streamlit/secrets.toml from .env, so the dashboard can reach MySQL.

Streamlit's st.connection reads its database settings from secrets.toml.
Generating that file from src/config.py keeps .env the only place where the
settings live. The file holds the password, so it is gitignored.
Run it once, and again after any change to the MYSQL_* values in .env:
    python scripts/make_secrets.py
"""
import json
import sys
from pathlib import Path

# Let `python scripts/make_secrets.py` import the src package from the repo root.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src import config  # noqa: E402

SECRETS = config.ROOT / ".streamlit" / "secrets.toml"


def main():
    # json.dumps puts quotes around each string and escapes any special
    # characters the way a TOML string expects.
    text = (
        "# Generated by scripts/make_secrets.py from .env. Do not edit or commit.\n"
        "[connections.mysql]\n"
        'dialect = "mysql"\n'
        'driver = "pymysql"\n'
        f"host = {json.dumps(config.MYSQL_HOST)}\n"
        f"port = {config.MYSQL_PORT}\n"
        f"database = {json.dumps(config.MYSQL_DATABASE)}\n"
        f"username = {json.dumps(config.MYSQL_USER)}\n"
        f"password = {json.dumps(config.MYSQL_PASSWORD)}\n"
    )
    SECRETS.parent.mkdir(exist_ok=True)
    SECRETS.write_text(text)
    print(f"Wrote {SECRETS.relative_to(config.ROOT)} (MySQL {config.MYSQL_HOST}:{config.MYSQL_PORT}, "
          f"database {config.MYSQL_DATABASE}, user {config.MYSQL_USER})")


if __name__ == "__main__":
    main()
